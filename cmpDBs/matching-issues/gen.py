#!/usr/bin/env python3
r"""Build the scripts and the catalog of cases from the sources.

  src/*.sql           -> node1.sql, node2.sql, node3.sql
  special/src/*.sql   -> special/<name>_node1.sql, special/<name>_node2.sql
  all of them and expected.csv -> diff-problem-cases.md

A source file is plain SQL with three psql-like marks at the start of a line:
\if :n1 | \if :n2 | \if :n3, \elif :nN, \else, \endif. The marks choose the
lines of one node. The output files are plain SQL without any mark.
"""
import csv
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NODE3_FILES = ('00_setup.sql', '80_three.sql', '99_finish.sql')

HEAD = """-- Reference database for the comparison of two PostgreSQL databases, node {n}.
-- Generated by gen.py from the files in src/. Do not edit.
--
-- Usage:  psql -X -q -v ON_ERROR_STOP=1 -d <database> -f node{n}.sql
--
-- The script drops and creates the schemas ref_meta, num, typ, eqv, txt, nul,
-- key, dty, lob, str, rep, ver, dmp in the current database. The table
-- ref_meta.cases says, for each table, which case it belongs to and what a
-- comparison of node 1 and node 2 should report.
"""


def render(path, node):
    out, stack = [], []          # stack of [taken_before, active]
    for raw in open(path, encoding='utf-8'):
        line = raw.rstrip('\n')
        m = re.match(r'\\(if|elif|else|endif)\b\s*(?::n(\d))?\s*$', line)
        if not m:
            if line.startswith('\\'):
                sys.exit('%s: unknown mark: %s' % (path, line))
            if all(f[1] for f in stack):
                out.append(line)
            continue
        kind, num = m.group(1), m.group(2)
        if kind == 'if':
            hit = int(num) == node
            stack.append([hit, hit])
        elif kind == 'elif':
            hit = int(num) == node and not stack[-1][0]
            stack[-1] = [stack[-1][0] or hit, hit]
        elif kind == 'else':
            hit = not stack[-1][0]
            stack[-1] = [True, hit]
        else:
            stack.pop()
    if stack:
        sys.exit('%s: \\if without \\endif' % path)
    return out


SPECIAL_HEAD = """-- {name}, node {n}. Generated by gen.py from special/src/{name}.sql.
-- Usage:  psql -X -q -v ON_ERROR_STOP=1 -d <database> -f {name}_node{n}.sql
--
"""
SPECIAL_SETUP = """
SET client_min_messages = warning;
SET TimeZone = 'UTC';
SET DateStyle = 'ISO, MDY';
SET IntervalStyle = 'postgres';
SET default_transaction_read_only = off;
CREATE SCHEMA IF NOT EXISTS sp;
"""

# special/src/<name>.sql -> special/<name>_node1.sql and special/<name>_node2.sql
for path in sorted(glob.glob(os.path.join(HERE, 'special', 'src', '*.sql'))):
    name = os.path.basename(path)[:-4]
    for node in (1, 2):
        body = render(path, node)
        k = 0
        while k < len(body) and body[k].startswith('--'):
            k += 1
        text = SPECIAL_HEAD.format(name=name, n=node) + '\n'.join(body[:k]) + '\n' + SPECIAL_SETUP + '\n'.join(body[k:]) + '\n'
        with open(os.path.join(HERE, 'special', '%s_node%d.sql' % (name, node)), 'w', encoding='utf-8') as f:
            f.write(text)
print('special: %d pairs' % len(glob.glob(os.path.join(HERE, 'special', 'src', '*.sql'))))

for node in (1, 2, 3):
    lines = [HEAD.format(n=node)]
    for path in sorted(glob.glob(os.path.join(HERE, 'src', '*.sql'))):
        name = os.path.basename(path)
        if node == 3 and name not in NODE3_FILES:
            continue
        lines.append('\n-- ' + '=' * 70 + '\n-- ' + name + '\n-- ' + '=' * 70)
        lines.extend(render(path, node))
    text = re.sub(r'\n{3,}', '\n\n', '\n'.join(lines)) + '\n'
    with open(os.path.join(HERE, 'node%d.sql' % node), 'w', encoding='utf-8') as f:
        f.write(text)
    print('node%d.sql: %d lines' % (node, text.count('\n')))


# ---------------------------------------------------------------------------
# diff-problem-cases.md: every case, its tables and the expected result.

SECTIONS = [('N', 'Numeric and float'), ('T', 'Types and table definitions'),
            ('E', 'Equal by the operator, different text'),
            ('X', 'Text output, session settings, encoding'),
            ('U', 'NULL and row encoding'), ('K', 'Keys'), ('D', 'Other data types'),
            ('L', 'OID columns and large objects'),
            ('S', 'Table structure, visibility, replication design'),
            ('R', 'Repair'), ('V', 'Verdict'), ('P', 'Dump, restore, pg_upgrade')]

CASES_HEAD = """# Cases and expected results

Generated by `gen.py` from `src/`, `special/src/` and `expected.csv`. Do not edit.

Each case is one situation where a comparison of two tables can give a wrong answer. The tables of the main set are made by `node1.sql` and `node2.sql`; the cases of the second part need a special stand and have their own script pairs in `special/`.

## How to read the tables

- **Expected result** is the text of the register `ref_meta.cases`: what a correct comparison of node 1 and node 2 reports. Text after the row counts describes a repair or a step of the test.
- **Text rule** gives three numbers: rows only on node 1 / rows only on node 2 / changed rows. A value is the text output of its type; rows are paired by the text of the key; two values are equal when the texts are byte-equal.
- **Operator rule** gives the same three numbers when rows are paired by the operator `=` of the key and values are compared with `IS DISTINCT FROM`. The column is empty when both rules give the same numbers.
- When the two rules give different numbers, both answers are possible for a correct tool. The tool must say which rule it follows, and its numbers must be the numbers of that rule.
- `n/a` means that the number cannot be computed; **Notes** says why. For a table without a usable key, whole rows are compared as a set with counts, and "changed" has no meaning.
- When **Notes** names a difference of the definitions (a type, a key, a column), a tool can also refuse the table with a clear message. A silent "match" is never right for a table with a number above zero.
- The numbers come from `expected.py`, which computes both rules from the loaded data. `expected.csv` holds them in a form for programs, with the row counts of each node.
"""


def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def case_order(cid):
    letters = [s[0] for s in SECTIONS]
    return letters.index(cid[0]), int(cid[1:])


def collect_titles(lines, titles):
    """Comment lines of the form '-- N1: title' or '-- N9, N17: title'."""
    i = 0
    while i < len(lines):
        m = re.match(r'-- ((?:[A-Z]\d+)(?:, [A-Z]\d+)*)(?: with three nodes)?: (.*)$', lines[i])
        if m:
            text = m.group(2)
            while i + 1 < len(lines) and lines[i + 1].startswith('-- ') and not re.match(r'-- [A-Z]\d+[,: ]', lines[i + 1]):
                i += 1
                text += ' ' + lines[i][3:].strip()
            for cid in m.group(1).split(', '):
                titles.setdefault(cid, text.rstrip('.'))
        i += 1


def numbers(row, prefix):
    vals = [row[prefix + k] for k in ('only_n1', 'only_n2', 'changed')]
    if vals[0] == '':
        return 'n/a'
    return ' / '.join(v if v != '' else 'n/a' for v in vals)


titles, register = {}, []
for path in sorted(glob.glob(os.path.join(HERE, 'src', '*.sql'))):
    for node in (1, 3):
        if node == 3 and os.path.basename(path) not in NODE3_FILES:
            continue
        body = render(path, node)
        collect_titles(body, titles)
        for line in body:
            m = re.match(r"CALL ref_meta\.reg\('([A-Z]\d+)', '((?:[^']|'')*)', '((?:[^']|'')*)'\);$", line)
            if m:
                entry = (m.group(1), m.group(2).replace("''", "'"), m.group(3).replace("''", "'"))
                if entry not in register:
                    register.append(entry)

expected = {}
expected_path = os.path.join(HERE, 'expected.csv')
if os.path.exists(expected_path):
    with open(expected_path, newline='', encoding='utf-8') as f:
        expected = {r['table']: r for r in csv.DictReader(f)}

out = [CASES_HEAD, '# Part 1. The main set\n']
for letter, name in SECTIONS:
    rows = sorted((e for e in register if e[0][0] == letter), key=lambda e: case_order(e[0]))
    if not rows:
        continue
    out.append('## %s. %s\n' % (letter, name))
    out.append('| Case | Table | Expected result | Text rule | Operator rule | Notes |')
    out.append('|---|---|---|---|---|---|')
    seen = set()
    for cid, tbl, expect in rows:
        if cid not in titles:
            sys.exit('no title comment for the case %s' % cid)
        first = '**%s** %s' % (cid, cell(titles[cid])) if cid not in seen else ''
        seen.add(cid)
        e = expected.get(tbl)
        text = numbers(e, 'text_') if e else ''
        oper = numbers(e, 'eq_') if e else ''
        notes = e['notes'] if e else ('not in expected.csv' * bool(expected))
        out.append('| %s | `%s` | %s | %s | %s | %s |' % (first, tbl, cell(expect), text, '' if oper == text else oper, cell(notes)))
    out.append('')

out.append('# Part 2. Cases that need a special stand\n')
out.append('The text of each case is the head of its script pair in `special/`. `Stand` says what the servers need, `Run` gives the steps, `Expect` is the expected result.\n')
special = []
for path in glob.glob(os.path.join(HERE, 'special', 'src', '*.sql')):
    body = render(path, 1)
    k = 0
    while k < len(body) and body[k].startswith('--'):
        k += 1
    head = [l[3:] if l.startswith('-- ') else l[2:] for l in body[:k]]
    m = re.match(r'Case ([A-Z]\d+)', head[0]) if head else None
    if not m:
        sys.exit('%s: the first line must be "-- Case <ID>..."' % path)
    special.append((case_order(m.group(1)), os.path.basename(path)[:-4], head))
for _, name, head in sorted(special):
    out.append('## `%s`\n' % name)
    out.append('```\n' + '\n'.join(head) + '\n```\n')

with open(os.path.join(HERE, 'diff-problem-cases.md'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(out))
print('diff-problem-cases.md: %d cases of the main set, %d script pairs' % (len({e[0] for e in register}), len(special)))
